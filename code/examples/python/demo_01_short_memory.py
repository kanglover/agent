def main():
    print("=" * 60)
    print("  Demo 01 — 短期记忆：存储 / 管理 / 压缩")
    print("=" * 60)

    mem = ShortTermMemory(max_turns=4)  # 4轮后触发压缩（方便演示）

    # 模拟一段对话
    conversations = [
        "你好，我叫小明",
        "我想学 Python",
        "Python 适合做 AI 吗？",
        "什么是 RAG？",
        "RAG 怎么防止幻觉？",
        # 第 5 轮超过阈值，触发压缩 ↑
        "我叫什么名字？",  # 测试：压缩后能否记住"小明"
    ]

    for i, user_input in enumerate(conversations, 1):
        print(f"\n{'─'*50}")
        print(f"  轮 {i} | 用户: {user_input}")
        reply = mem.chat(user_input)
        print(f"       助手: {reply}")

    mem.show_state()

    print("\n" + "=" * 60)
    print("  关键结论：")
    print("  1. 短期记忆 = messages 列表，随对话增长")
    print("  2. 超过阈值 → 压缩旧消息为摘要，注入 system")
    print("  3. 压缩后历史不丢失，但换了更紧凑的形式")
    print("=" * 60)


if __name__ == "__main__":
    main()

