MODEL = "claude-opus-4-8"

# 创建一个全局 client。
# 不用在这里填 API key —— SDK 会自动从环境变量 ANTHROPIC_API_KEY 读取，
# 或者从 `ant auth login` 登录后的 profile 读取。
client = anthropic.Anthropic()


# ─────────────────────────────────────────────────────────────
# 真实 LLM 调用（Anthropic Claude API）
# ─────────────────────────────────────────────────────────────

def call_llm(messages: list[dict], system: str = "") -> str:
    """
    调用真实的 Claude API。

    messages: 对话历史，格式 [{"role": "user"/"assistant", "content": "..."}]
    system:   system prompt（历史摘要会拼到这里注入）
    返回:     模型的回复文本
    """
    last_user_msg = next(
        (m["content"] for m in reversed(messages) if m["role"] == "user"), ""
    )
    print(f"    [LLM收到] system前缀={system[:40]!r}... | 最后一条用户消息={last_user_msg!r}")

    # 真正的 API 调用：把完整对话历史 + system prompt 一起发给 Claude
    response = client.messages.create(
        model=MODEL,
        max_tokens=1024,  # 这只是个聊天演示，1024 token 足够回复了
        system=system,
        messages=messages,
    )

    # response.content 是一个内容块列表（文本块、思考块等）。
    # 取出第一个文本块的文字作为回复。
    return next(
        (block.text for block in response.content if block.type == "text"), ""
    )


# ─────────────────────────────────────────────────────────────
# 短期记忆管理器
# ─────────────────────────────────────────────────────────────

class ShortTermMemory:
    """
    短期记忆：基于 messages 列表管理对话历史

    超过 max_turns 时自动压缩：
      把最早的几轮 → 摘要 → 注入 system prompt
    """

    def __init__(self, max_turns: int = 6):
        self.messages: list[dict] = []  # 核心存储：就是一个列表
        self.max_turns = max_turns       # 超过这个轮数触发压缩
        self.summary: str = ""           # 历史摘要（压缩后保留的精华）
        self.turn_count: int = 0

    def add_user(self, content: str):
        self.messages.append({"role": "user", "content": content})

    def add_assistant(self, content: str):
        self.messages.append({"role": "assistant", "content": content})
        self.turn_count += 1
        # 超过阈值 → 触发压缩
        if self.turn_count > 0 and self.turn_count % self.max_turns == 0:
            self._compress()

    def _compress(self):
        """
        压缩策略：把前 N 轮消息 → 请 LLM 摘要 → 替换原消息

        这就像会议记录员：
          原始记录太长 → 整理成一页摘要 → 存档原始内容 → 继续记后续内容
        """
        if len(self.messages) < 4:
            return

        # 取前一半消息用于压缩
        cutoff = len(self.messages) // 2
        old_msgs = self.messages[:cutoff]
        self.messages = self.messages[cutoff:]  # 只保留后半段

        # 请 LLM 生成摘要
        summary_prompt = [
            {"role": "user", "content": f"请用2-3句话总结以下对话的关键信息：\n{old_msgs}"}
        ]
        new_summary = call_llm(summary_prompt)

        # 累积摘要（新摘要追加到旧摘要后面）
        if self.summary:
            self.summary += f"\n{new_summary}"
        else:
            self.summary = new_summary

        print(f"\n  ⚡ [自动压缩] 已将 {cutoff} 条旧消息压缩为摘要")
        print(f"     摘要内容: {self.summary[:80]}...")

    def get_system_prompt(self) -> str:
        """把历史摘要注入 system prompt，让 LLM 知道"之前发生了什么" """
        if self.summary:
            return f"[历史对话摘要]\n{self.summary}\n\n你是一个友好的 AI 助手。"
        return "你是一个友好的 AI 助手。"

    def chat(self, user_input: str) -> str:
        """一轮完整对话"""
        self.add_user(user_input)
        system = self.get_system_prompt()
        reply = call_llm(self.messages, system=system)
        self.add_assistant(reply)
        return reply

    def show_state(self):
        """可视化当前内存状态"""
        print(f"\n  📋 当前内存状态:")
        print(f"     - messages 列表: {len(self.messages)} 条")
        print(f"     - 累计对话轮数: {self.turn_count}")
        print(f"     - 历史摘要: {'有' if self.summary else '无'} ({len(self.summary)} 字)")
        for i, m in enumerate(self.messages[-4:]):  # 只显示最近4条
            print(f"     [{m['role']:>9}] {m['content'][:50]}")


