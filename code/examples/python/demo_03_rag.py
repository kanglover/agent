# ① 分块（Chunking）
# ─────────────────────────────────────────────────────────────

def chunk_documents(docs: list[str], chunk_size: int = 150, overlap: int = 30) -> list[dict]:
    """
    把文档切成小块（带重叠）

    chunk_size: 每块最大字数
    overlap:    相邻块重叠字数（防止关键信息被切断，比如价格跨两个块）
    """
    chunks = []
    for doc_id, doc in enumerate(docs):
        text = re.sub(r'\s+', ' ', doc.strip())  # 清理多余空白

        if len(text) <= chunk_size:
            chunks.append({"id": f"d{doc_id}_c0", "text": text, "doc_id": doc_id})
        else:
            start, idx = 0, 0
            while start < len(text):
                end = min(start + chunk_size, len(text))
                chunks.append({"id": f"d{doc_id}_c{idx}", "text": text[start:end], "doc_id": doc_id})
                if end == len(text):
                    break
                start += chunk_size - overlap
                idx += 1

    return chunks


# ─────────────────────────────────────────────────────────────
# ② 索引（TF-IDF 向量化）
# ─────────────────────────────────────────────────────────────

def tokenize(text: str) -> list[str]:
    """分词（中文按字，英文按词）"""
    return re.findall(r'[一-鿿]|[a-zA-Z0-9]+', text.lower())


def build_index(chunks: list[dict]) -> tuple[list[dict], dict]:
    """
    建立 TF-IDF 向量索引

    真实场景：调用 Embedding 模型（如 text-embedding-3-small）
             把文本变成 1536 维的语义向量
    这里用 TF-IDF：把文本变成「词频权重」稀疏向量
    两者最终都是：文本 → 数字向量 → 余弦相似度检索
    """
    texts = [c["text"] for c in chunks]
    n = len(texts)
    tokenized = [tokenize(t) for t in texts]

    # IDF：词的全局权重（越稀有的词，权重越高）
    doc_freq = Counter()
    for toks in tokenized:
        doc_freq.update(set(toks))
    idf = {term: math.log((n + 1) / (df + 1)) for term, df in doc_freq.items()}

    # TF-IDF 向量
    vectors = []
    for toks in tokenized:
        tf = Counter(toks)
        total = len(toks) or 1
        vec = {t: (tf[t] / total) * idf.get(t, 0) for t in tf}
        vectors.append(vec)

    return vectors, idf


def cosine_sim(a: dict, b: dict) -> float:
    """余弦相似度（0~1，越大越相似）"""
    common = set(a) & set(b)
    if not common:
        return 0.0
    dot = sum(a[t] * b[t] for t in common)
    na = math.sqrt(sum(v * v for v in a.values()))
    nb = math.sqrt(sum(v * v for v in b.values()))
    return dot / (na * nb) if na * nb else 0.0


# ─────────────────────────────────────────────────────────────
# ③ 检索（Retrieval）
# ─────────────────────────────────────────────────────────────

def retrieve(query: str, chunks: list[dict], vectors: list[dict], idf: dict,
             top_k: int = 2) -> list[dict]:
    """
    用 TF-IDF 余弦相似度检索最相关的 Top-K 块

    真实场景：query → Embedding → 在向量库中做近似最近邻搜索（ANN）
    这里：    query → TF-IDF向量 → 暴力计算所有相似度 → 取 Top-K
    """
    q_toks = tokenize(query)
    q_tf = Counter(q_toks)
    q_total = len(q_toks) or 1
    q_vec = {t: (q_tf[t] / q_total) * idf.get(t, 0) for t in q_tf}

    scored = []
    for chunk, vec in zip(chunks, vectors):
        sim = cosine_sim(q_vec, vec)
        scored.append({**chunk, "similarity": round(sim, 3)})

    scored.sort(key=lambda x: x["similarity"], reverse=True)
    return scored[:top_k]


# ─────────────────────────────────────────────────────────────
# ④ 生成（Generation）
# ─────────────────────────────────────────────────────────────

RAG_SYSTEM = """你是客服助手。

【参考资料】
{context}

【规则】
1. 只根据【参考资料】回答，不得编造
2. 资料中没有的，明确说"资料中没有相关记录"
"""

def rag_answer(query: str, chunks, vectors, idf) -> dict:
    """完整 RAG 流程"""
    hits = retrieve(query, chunks, vectors, idf, top_k=2)
    context = "\n---\n".join(h["text"] for h in hits if h["similarity"] > 0.01)
    system = RAG_SYSTEM.format(context=context) if context else "你是客服助手。"
    answer = call_llm(system=system, user=query)
    return {"query": query, "hits": hits, "answer": answer, "has_context": bool(context)}


def no_rag_answer(query: str) -> str:
    """无 RAG 对比"""
    return call_llm(system="你是客服助手。", user=query)


